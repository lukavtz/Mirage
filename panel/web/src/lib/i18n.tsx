export type Lang = keyof typeof messages
export type TranslationKey = keyof typeof messages['en']

const STORAGE_KEY = 'lang'

// ── date-fns locale mapping ─────────────────────────────────────────
export const dateLocales: Record<Lang, Locale> = {
  en: undefined as unknown as Locale, // date-fns default is English
  ru: dateFnsRu,
}

// ── React Context ───────────────────────────────────────────────────
interface I18nContextType {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: TranslationKey, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextType | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'en'
    return (localStorage.getItem(STORAGE_KEY) as Lang) ?? 'en'
  })

  const setLang = useCallback((newLang: Lang) => {
    localStorage.setItem(STORAGE_KEY, newLang)
    setLangState(newLang)
  }, [])

  const t = useCallback((key: TranslationKey, params?: Record<string, string | number>): string => {
    let text: string = messages[lang]?.[key] ?? messages['en']?.[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(`{${k}}`, String(v))
      }
    }
    return text
  }, [lang])

  // Update document lang attribute
  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

// ── Standalone t() for use outside React components ─────────────────
// Reads from localStorage directly. Components should use useI18n().t instead.
export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  const lang: Lang = (typeof window !== 'undefined'
    ? (localStorage.getItem(STORAGE_KEY) as Lang)
    : null) ?? 'en'
  let text: string = messages[lang]?.[key] ?? messages['en']?.[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}

// ── Compat exports (to be removed after migration) ──────────────────
export function getLang(): Lang {
  if (typeof window === 'undefined') return 'en'
  return (localStorage.getItem(STORAGE_KEY) as Lang) ?? 'en'
}

export function setLang(lang: Lang) {
  if (typeof window === 'undefined') return
  localStorage.setItem(STORAGE_KEY, lang)
}
